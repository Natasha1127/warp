/** マイクロ単元ID（"g4-u3-mu1"）→ 単元ID（"g4-u3"） */
export function microUnitToUnitId(microUnitId: string): string {
  return microUnitId.replace(/-mu1$/, "");
}

/** 単元ID（"g4-u3"）→ マイクロ単元ID（"g4-u3-mu1"） */
export function unitToMicroUnitId(unitId: string): string {
  return `${unitId}-mu1`;
}

/**
 * あるマイクロ単元の前提となるマイクロ単元IDを返す。無ければ null。
 */
export function prerequisiteMicroUnitId(microUnitId: string): string | null {
  const unitId = microUnitToUnitId(microUnitId);
  const prereqUnit = UNIT_PREREQUISITE[unitId];
  return prereqUnit ? unitToMicroUnitId(prereqUnit) : null;
}
